use crate::edwards448::*;

#[test]
fn test_bytes_to_field() {
    let bytes: [u8; BYTES] = [
        0xd3, 0x0a, 0x60, 0x1c, 0x4f, 0x9a, 0x25, 0x29, 0x4b, 0xf5, 0x68, 0xa3, 0xeb, 0x43, 0x49,
        0xf4, 0xbf, 0x8f, 0xd7, 0xcd, 0xf8, 0x24, 0x4c, 0x98, 0x9c, 0x77, 0x0a, 0x70, 0x21, 0xe1,
        0xaa, 0xd1, 0xd0, 0x04, 0x51, 0x04, 0xef, 0xac, 0x82, 0x88, 0xd2, 0x34, 0x9a, 0xa1, 0xfe,
        0x66, 0x52, 0x49, 0x88, 0x8e, 0xec, 0xf9, 0xdd, 0x2f, 0x26, 0x3d,
    ];
    let expected = Field448 {
        x: [
            10584238707444435,
            19117910512716585,
            70032119937627209,
            31536706236206116,
            22804768030908705,
            14868182538710788,
            38361215096758682,
            17211960608812174,
        ],
    };

    let actual = Field448::from(bytes.to_vec());
    assert_eq!(actual, expected);
}

#[test]
fn test_field_to_bytes() {
    let field = Field448 {
        x: [
            10584238707444435,
            19117910512716585,
            70032119937627209,
            31536706236206116,
            22804768030908705,
            14868182538710788,
            38361215096758682,
            17211960608812174,
        ],
    };
    let expected: [u8; BYTES + 1] = [
        0xd3, 0x0a, 0x60, 0x1c, 0x4f, 0x9a, 0x25, 0x29, 0x4b, 0xf5, 0x68, 0xa3, 0xeb, 0x43, 0x49,
        0xf4, 0xbf, 0x8f, 0xd7, 0xcd, 0xf8, 0x24, 0x4c, 0x98, 0x9c, 0x77, 0x0a, 0x70, 0x21, 0xe1,
        0xaa, 0xd1, 0xd0, 0x04, 0x51, 0x04, 0xef, 0xac, 0x82, 0x88, 0xd2, 0x34, 0x9a, 0xa1, 0xfe,
        0x66, 0x52, 0x49, 0x88, 0x8e, 0xec, 0xf9, 0xdd, 0x2f, 0x26, 0x3d, 0x00,
    ];

    let actual: [u8; BYTES + 1] = field.into();
    assert_eq!(actual, expected);
}
